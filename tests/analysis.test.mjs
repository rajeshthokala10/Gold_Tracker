// Unit tests for the analysis engine. Fixtures here are hand-made test
// inputs used only to check arithmetic; they are never shown on the site.
import test from "node:test";
import assert from "node:assert/strict";
import * as A from "../site/js/analysis.js";

const close = (a, b, eps = 1e-9) => assert.ok(Math.abs(a - b) < eps, `${a} != ${b}`);

test("ISO weeks: year boundaries and week 53", () => {
  assert.equal(A.isoWeek("2024-12-30").key, "2025-W01"); // Monday belongs to 2025
  assert.equal(A.isoWeek("2025-12-28").key, "2025-W52");
  assert.equal(A.isoWeek("2026-12-31").key, "2026-W53");
  assert.equal(A.isoWeek("2027-01-03").key, "2026-W53"); // Sunday still 2026-W53
  assert.equal(A.isoWeek("2027-01-04").key, "2027-W01");
  assert.equal(A.isoWeek("2021-01-03").key, "2020-W53");
  assert.equal(A.isoWeek("2022-01-02").key, "2021-W52");
  assert.deepEqual([2022, 2023, 2024, 2025, 2026].map(A.weeksInIsoYear), [52, 52, 52, 52, 53]);
});

test("weekly: last valid price of the week, previous week's last price as base", () => {
  const pts = [
    ["2025-01-06", 100], ["2025-01-08", 104], ["2025-01-10", 102], // W02 last = 102
    ["2025-01-13", 103], ["2025-01-17", 107.1],                     // W03 last = 107.1
  ];
  const w = A.toWeekly(pts, "2025-01-31");
  assert.equal(w.length, 2);
  assert.equal(w[0].status, "first");
  assert.equal(w[0].price, 102);
  assert.equal(w[0].obs, 3);
  assert.equal(w[1].status, "ok");
  close(w[1].chg, 5.1);
  close(w[1].ret, 0.05);
});

test("weekly: holiday week with one observation still counts; empty week is a gap", () => {
  const pts = [
    ["2025-01-10", 100],   // W02
    ["2025-01-15", 101],   // W03 single obs (holidays)
    // W04 no data
    ["2025-01-31", 110],   // W05
    ["2025-02-07", 99],    // W06
  ];
  const w = A.toWeekly(pts, "2025-03-01");
  assert.deepEqual(w.map((x) => x.status), ["first", "ok", "missing", "gap", "ok"]);
  assert.equal(w[2].price, null); // never filled in
  close(w[3].ret, 110 / 101 - 1); // measured from W03 but excluded from ranking
  assert.deepEqual(A.rankable(w).map((x) => x.key), ["2025-W03", "2025-W06"]);
});

test("weekly: unfinished current week is partial and not ranked", () => {
  const pts = [["2026-10-16", 100], ["2026-10-21", 101]];
  const w = A.toWeekly(pts, "2026-10-23"); // Friday; week ends Sunday 25th
  assert.equal(w[1].status, "partial");
  assert.equal(A.rankable(w).length, 0);
  assert.equal(A.lastCompleteIndex(w), 0);
});

test("weekly: ignores invalid prices instead of inventing them", () => {
  const w = A.toWeekly([["2025-01-06", 100], ["2025-01-13", NaN], ["2025-01-14", 0], ["2025-01-20", 101]], "2025-02-01");
  assert.deepEqual(w.map((x) => x.status), ["first", "missing", "gap"]);
});

function syntheticYears(years, fn) {
  // One price per Friday, generated by fn(year, isoWeek) -> weekly return.
  const pts = [];
  let p = 1000;
  let t = A.isoWeek(`${years[0] - 1}-12-25`).monday; // a Monday
  const end = A.parseDate(`${years[years.length - 1]}-12-31`);
  while (t <= end) {
    const iw = A.isoWeek(t);
    p *= 1 + fn(iw.y, iw.w);
    pts.push([A.fmtDate(t + 4 * 86400000), p]);
    t += 7 * 86400000;
  }
  return pts;
}

test("seasonal stats, rankings and consistency labels", () => {
  const years = [2022, 2023, 2024, 2025];
  const pts = syntheticYears(years, (y, w) => (w === 10 ? 0.02 : w === 20 ? (y === 2023 ? 0.08 : -0.01) : w === 30 ? -0.02 : 0));
  const weeks = A.toWeekly(pts, "2026-06-01");
  const st = A.seasonalStats(weeks, years);
  assert.equal(st[10].n, 4);
  close(st[10].mean, 0.02);
  assert.equal(st[10].consistency.code, "consistent");
  assert.equal(st[20].consistency.code, "outlier");
  assert.equal(st[20].consistency.year, 2023);
  const rk = A.rankSeasonal(st);
  assert.equal(rk.strongest[0].w, 10);
  assert.equal(rk.weakest[0].w, 30);
  const tb = A.topBottomByYear(weeks, [2023]);
  assert.equal(tb[2023].top[0].w, 20);
  assert.equal(tb[2023].bottom[0].w, 30);
});

test("costs: physical and ETF round trips", () => {
  const c = { physical: { gstPct: 3, premiumPct: 2, resalePct: 1 }, etf: { txnPct: 0.1, halfSpreadPct: 0.2 } };
  close(A.netReturn(100, 110, "physical", c), (110 * 0.99) / (100 * 1.02 * 1.03) - 1);
  close(A.netReturn(100, 110, "etf", c), (110 * 0.998 * 0.999) / (100 * 1.002 * 1.001) - 1);
  close(A.netReturn(100, 110, "etf", null), 0.1);
});

test("forward returns exclude incomplete windows and report drawdown", () => {
  const pts = [["2025-01-10", 100], ["2025-01-17", 90], ["2025-01-24", 120], ["2025-01-31", 110]];
  const w = A.toWeekly(pts, "2025-02-02");
  const f = A.forwardReturns(w, 2, "etf", null);
  assert.equal(f.length, 2); // entries W02 and W03 only
  close(f[0].ret, 0.2);
  close(f[0].maxDD, -0.1);
  close(f[1].ret, 110 / 90 - 1);
  close(f[1].maxDD, 110 / 120 - 1);
  assert.equal(A.forwardReturns(A.toWeekly(pts, "2025-01-30"), 2, "etf", null).length, 1); // last week partial
});

test("walk-forward never trains on data whose window reaches the test year", () => {
  const years = [2022, 2023, 2024, 2025];
  // Week 10 is great every year except the test years — a pure look-ahead
  // trap: if the test year leaked into training, week 10 would be chosen for
  // 2022-based tests incorrectly.
  const pts = syntheticYears(years, (y, w) => (w === 10 ? 0.03 : 0.0005));
  const weeks = A.toWeekly(pts, "2026-03-01");
  const wf = A.walkForward(weeks, 4, "etf", null, [2023, 2024, 2025], 1);
  for (const r of wf.rows) {
    assert.ok(r.trainYears.every((y) => y < r.year));
  }
  // 2023 can only train on one prior year, below the 2-year minimum, so it
  // makes no pick rather than trusting a single observation.
  assert.deepEqual(wf.rows[0].chosen, []);
  assert.equal(wf.rows[0].edge, null);
  assert.ok(wf.rows.slice(1).every((r) => r.chosen.length === 1 && r.chosen[0] >= 6 && r.chosen[0] <= 9));
  assert.equal(wf.valid, 2);
  assert.ok(wf.avgEdge > 0);
});

test("evidence labels are never stronger than exploratory", () => {
  assert.equal(A.evidenceLabel(3, 3, 0.01).code, "exploratory-consistent");
  assert.equal(A.evidenceLabel(3, 1, 0.01).code, "no-edge");
  assert.equal(A.evidenceLabel(2, 2, -0.01).code, "no-edge");
  assert.equal(A.evidenceLabel(0, 0, null).code, "none");
});

test("strategy comparison invests equal amounts over the same period", () => {
  const years = [2022, 2023, 2024, 2025];
  const pts = syntheticYears(years, () => 0.002);
  const weeks = A.toWeekly(pts, "2026-03-01");
  const r = A.compareStrategies(weeks, { amount: 120000, startYear: 2024, kind: "etf", costs: A.DEFAULT_COSTS });
  assert.equal(r.lump.invested, 120000);
  close(r.monthly.invested + r.monthly.cashLeft, 120000, 1e-6);
  close(r.seasonal.invested + r.seasonal.cashLeft, 120000, 1e-6);
  assert.ok(r.lump.value > r.monthly.value); // steadily rising price favours lump sum
  assert.ok(r.monthly.buys >= 24);
  assert.equal(r.lump.maxDD <= 0, true);
});

test("latest change and common-date comparison", () => {
  const a = [["2026-10-14", 100], ["2026-10-21", 104], ["2026-10-22", 105]];
  const lc = A.latestChange(a);
  close(lc.dayChg, 1);
  assert.equal(lc.wkDate, "2026-10-14");
  close(lc.wkChg, 5);
  const b = [["2026-10-21", 103], ["2026-10-23", 999]];
  assert.deepEqual(A.latestCommonDate(a, b), { date: "2026-10-21", a: 104, b: 103 });
});
